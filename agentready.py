#!/usr/bin/env python3
"""AgentReady: local-first, no-telemetry, opt-in bootstrap planner (Python stdlib)."""
from __future__ import annotations
import argparse
import datetime as dt
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import tempfile

from agentready_connectors import PROBES, verify as verify_connector
from agentready_native import build_personal_brief
from agentready_lark import LarkError, build_brief, markdown_brief
from agentready_delivery import publish_report
from agentready_weekly import build_weekly_review, markdown_weekly, read_config

ROOT = Path(__file__).resolve().parent
REGISTRY = ROOT / 'registry' / 'adapters.json'
PROFILES = ROOT / 'profiles'
CAPABILITIES = ROOT / 'registry' / 'capabilities.json'
VALID_PACKAGE = re.compile(r'^[a-zA-Z0-9][a-zA-Z0-9@._+/-]*$')


def load_json(path: Path):
    with path.open('r', encoding='utf-8') as f:
        return json.load(f)


def catalog():
    return load_json(REGISTRY)['adapters']


def profiles():
    return sorted(p.stem for p in PROFILES.glob('*.json'))


def resolved(profile_name: str, config_path: str | None = None):
    file = PROFILES / f'{profile_name}.json'
    if profile_name not in profiles():
        raise ValueError(f'Unknown profile {profile_name!r}. Choose: {", ".join(profiles())}')
    profile = load_json(file)
    config = load_json(Path(config_path)) if config_path else {}
    if not isinstance(config, dict):
        raise ValueError('Configuration must be a JSON object')
    enabled = config.get('enable', [])
    disabled = config.get('disable', [])
    if not isinstance(enabled, list) or not all(isinstance(s, str) for s in enabled):
        raise ValueError('Config enable must be a list of adapter names')
    if not isinstance(disabled, list) or not all(isinstance(s, str) for s in disabled):
        raise ValueError('Config disable must be a list of adapter names')
    components = list(dict.fromkeys(profile['components'] + enabled))
    components = [s for s in components if s not in disabled]
    adapters = catalog()
    missing = [c for c in components if c not in adapters]
    if missing:
        raise ValueError('Unknown adapters in profile or config: ' + ', '.join(missing))
    return [(cid, adapters[cid]) for cid in components]


def detect(adapter: dict):
    """Presence-only check. Does not access private content or credentials."""
    probe = adapter.get('probe', {})
    commands = probe.get('commands', [])
    apps = probe.get('mac_apps', [])
    if not commands and not apps:
        return 'external / unverified'
    cli = any(shutil.which(c) for c in commands)
    app = platform.system() == 'Darwin' and any(
        (Path('/Applications') / name).exists() or
        (Path('/System/Applications') / name).exists() or
        (Path.home() / 'Applications' / name).exists() for name in apps
    )
    return 'found locally (access not verified)' if (cli or app) else 'not detected'


def checks(items):
    return [{"adapter": id_, "label": spec['label'], "category": spec['category'],
             "detected": detect(spec), "purpose": spec['purpose'],
             "requires_manual_setup": spec.get('setup', []),
             "macos_install": spec.get('macos_install', {})}
            for id_, spec in items]


def bundle(items):
    if platform.system() != 'Darwin':
        # Brewfile still expressible for Mac when authored on another OS.
        pass
    lines = ['# Generated by AgentReady (review before applying).',
             '# Homebrew installs on macOS; remote services and Apple built-ins are not installed here.']
    seen = set()
    for _, spec in items:
        install = spec.get('macos_install', {})
        for section in ('brew', 'cask'):
            for package in install.get(section, []):
                if not VALID_PACKAGE.fullmatch(package):
                    raise ValueError('Unsafe package token in registry: ' + package)
                entry = f'{section} "{package}"'
                if entry not in seen:
                    seen.add(entry)
                    lines.append(entry)
    return '\n'.join(lines) + '\n'


def summary(profile: str, items, json_mode: bool):
    details = checks(items)
    if json_mode:
        print(json.dumps({'profile': profile, 'platform': platform.system(),
                          'components': details}, ensure_ascii=False, indent=2))
        return
    print(f'AgentReady | profile={profile} | OS={platform.system()} | {len(details)} adapters')
    for d in details:
        print(f'  [{d["detected"]}] {d["label"]}: {d["purpose"]}')
        if d['requires_manual_setup']:
            print('     Manual: ' + ' / '.join(d['requires_manual_setup']))
    print('\nNo app data, private messages, tokens or secrets have been read.')


def apply_brewfile(contents: str):
    if platform.system() != 'Darwin':
        raise RuntimeError('Automated installation v0.1 supports macOS only; other OS: planning only.')
    if not shutil.which('brew'):
        raise RuntimeError('Homebrew missing. Install it via https://brew.sh/ after reviewing the official instructions.')
    if not any(line.startswith(('brew "', 'cask "')) for line in contents.splitlines()):
        print('No macOS packages are specified. Nothing to install.')
        return
    # File removed on exit. Explicit --apply is required; never run cleanup or upgrade.
    with tempfile.TemporaryDirectory(prefix='agentready-') as work:
        path = Path(work) / 'Brewfile'
        path.write_text(contents, encoding='utf-8')
        print('Running Homebrew Bundle (no upgrades, no cleanup).', flush=True)
        subprocess.run(['brew', 'bundle', 'install', '--no-upgrade', f'--file={path}'], check=True)


def inventory(items, outfile: str | None):
    payload = {
        'format': 'agentready-inventory-v1',
        'timestamp_utc': dt.datetime.now(dt.timezone.utc).isoformat(),
        'os': platform.system(),
        'os_release': platform.release(),
        'architecture': platform.machine(),
        'components': [{'id': n, 'detected': detect(s)} for n, s in items],
        'safety_note': 'This is a presence-only inventory. No credentials or user content included.'
    }
    data = json.dumps(payload, ensure_ascii=False, indent=2) + '\n'
    if outfile:
        target = Path(outfile).expanduser()
        if target.exists():
            raise RuntimeError(f'Refusing to overwrite existing inventory: {target}')
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(data, encoding='utf-8')
        print(f'Sanitized inventory created: {target}')
    else:
        print(data)




def write_new(path: str, data: str):
    dest = Path(path).expanduser()
    if dest.exists():
        raise RuntimeError(f'Refusing to overwrite existing file: {dest}')
    dest.parent.mkdir(parents=True, exist_ok=True)
    # Prevent a public-readable file containing personal choices or status.
    fd = os.open(str(dest), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, 'w', encoding='utf-8') as handle:
        handle.write(data)
    return dest


def capability_coverage(items):
    chosen = {key for key, _ in items}
    out = []
    for cap in load_json(CAPABILITIES)['capabilities']:
        providers = [key for key in cap['providers'] if key in chosen]
        out.append({'capability': cap['id'], 'label': cap['label'],
                    'selected_providers': providers,
                    'state': 'selected_not_verified' if providers else 'not_selected',
                    'rule': cap['rule']})
    return out


def create_wizard_config(profile_name: str, ask=input):
    """Interactively collect nonsecret adapter choices. No provider login occurs."""
    profile = load_json(PROFILES / f'{profile_name}.json')
    defaults = set(profile['components'])
    print(f'AgentReady setup wizard | preset={profile_name}')
    print('Choose app integrations; no accounts, tokens or permissions are requested.')
    enabled, disabled = [], []
    for key, spec in catalog().items():
        default = key in defaults
        suffix = '[Y/n]' if default else '[y/N]'
        answer = ask(f'  {spec["label"]} {suffix}: ').strip().lower()
        if answer not in ('', 'y', 'yes', 'n', 'no'):
            raise ValueError('Please answer Y or N and restart the wizard')
        choice = default if not answer else answer in ('y', 'yes')
        if choice and not default:
            enabled.append(key)
        elif default and not choice:
            disabled.append(key)
    return {'enable': enabled, 'disable': disabled}


def offline_report(profile_name: str, items):
    lines = [f'# AgentReady onboarding report — {profile_name}', '',
             'Local presence checks only; no accounts, tokens, events or files were read.', '',
             '## Selected components', '']
    for name, spec in items:
        lines.append(f'- **{spec["label"]}** (`{name}`): {detect(spec)}')
        for action in spec.get('setup', []):
            lines.append(f'  - [ ] {action}')
    lines.extend(['', '## Capability ownership (selection ≠ verified connection)', ''])
    for cap in capability_coverage(items):
        selected = ', '.join(cap['selected_providers']) or 'not selected'
        lines.append(f'- **{cap["label"]}**: {selected}. {cap["rule"]}')
    lines.extend(['', '## Next verification gates', '',
                  '- [ ] Confirm local app launches and native login in each service',
                  '- [ ] Confirm actual owner, account and company/personal boundary',
                  '- [ ] Verify CLI/MCP/API authentication (never copy tokens into reports)',
                  '- [ ] Validate permitted sample read, denied writes and source links',
                  '- [ ] Confirm phone and desktop user journey with real UI',
                  '- [ ] Record backup/restore and single authoritative scheduler',
                  '', 'No connector endpoint was automatically contacted.'])
    return '\n'.join(lines) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description='AgentReady: portable AI productivity environment planner')
    sub = parser.add_subparsers(dest='command', required=True)
    for cmd in ['doctor', 'plan', 'permissions', 'inventory', 'brewfile', 'install']:
        sp = sub.add_parser(cmd)
        sp.add_argument('--profile', choices=profiles(), default='starter')
        sp.add_argument('--config', help='local JSON with enable/disable adapter IDs (no secrets)')
        if cmd in ('doctor', 'plan'):
            sp.add_argument('--json', action='store_true')
        if cmd == 'inventory':
            sp.add_argument('--output', help='explicit output filename; existing files are never overwritten')
        if cmd == 'brewfile':
            sp.add_argument('--output', help='explicit output filename; existing files are never overwritten')
        if cmd == 'install':
            sp.add_argument('--apply', action='store_true', help='required to actually install anything')
    sub.add_parser('catalog')
    cover = sub.add_parser('coverage', help='Show selected providers and missing capability areas, offline')
    cover.add_argument('--profile', choices=profiles(), default='starter')
    cover.add_argument('--config')
    cover.add_argument('--json', action='store_true')
    wizard = sub.add_parser('wizard', help='Create a nonsecret personal profile interactively')
    wizard.add_argument('--profile', choices=profiles(), default='starter')
    wizard.add_argument('--output', required=True, help='Must be a new, private local JSON path')
    report = sub.add_parser('report', help='Generate an offline setup and verification checklist')
    report.add_argument('--profile', choices=profiles(), default='starter')
    report.add_argument('--config')
    report.add_argument('--output', help='New Markdown report; prints to stdout if omitted')
    verify_cmd = sub.add_parser('verify', help='Explicit fixed-route safe connector reachability check')
    verify_cmd.add_argument('--service', required=True, choices=sorted(PROBES))
    verify_cmd.add_argument('--url', required=True, help='Service origin, not a resource URL')
    verify_cmd.add_argument('--live', action='store_true', help='Explicitly allow network request')
    verify_cmd.add_argument('--allow-remote', action='store_true', help='Allow HTTPS non-loopback origin')
    verify_cmd.add_argument('--token-env', help='Env variable containing temporary provider token (never echoed)')
    verify_cmd.add_argument('--mcp', action='store_true', help='NocoBase MCP initialize only, no tools/calls')
    brief = sub.add_parser('brief', help='Read-only lark-cli tasks/calendar daily brief; Hermes optional')
    brief.add_argument('--lark-profile', help='Existing lark-cli profile; never changes authentication')
    brief.add_argument('--provider', choices=['lark-cli'], default='lark-cli')
    brief.add_argument('--date', default=dt.datetime.now().date().isoformat(), help='YYYY-MM-DD in system-local timezone')
    brief.add_argument('--live', action='store_true', help='Call local authenticated lark-cli; otherwise offline')
    brief.add_argument('--fixture-dir', help='Explicit synthetic JSON fixtures (offline testing)')
    brief.add_argument('--message-query', help='Explicit keyword for scoped Feishu search; none by default')
    brief.add_argument('--details', action='store_true', help='Show up to 30 record titles and links per source')
    brief.add_argument('--format', choices=['markdown','json'], default='markdown')
    brief.add_argument('--output', help='Create NEW private report file, never overwrite')
    personal = sub.add_parser('personal-brief', help='Personal calendar/reminder/activity counts via installed native CLIs')
    personal.add_argument('--date', default=dt.date.today().isoformat())
    personal.add_argument('--live', action='store_true')
    personal.add_argument('--output', help='New private JSON report')
    weekly = sub.add_parser('weekly-review', help='Collect private evidence for the existing agent to write daily/weekly reports')
    weekly.add_argument('--date', default=dt.date.today().isoformat(), help='Weekly: collect previous Monday-Sunday; daily: collect this date')
    weekly.add_argument('--config', help='Private review configuration (no secrets)')
    weekly.add_argument('--period', choices=['daily', 'weekly'], default='weekly')
    weekly.add_argument('--live', action='store_true', help='Explicitly read configured sources')
    weekly.add_argument('--fixture-dir', help='Synthetic Feishu fixtures for offline tests')
    weekly.add_argument('--format', choices=['markdown', 'json'], default='markdown')
    weekly.add_argument('--output', help='Create NEW private report file, never overwrite')
    delivery = sub.add_parser('publish-report', help='Preview or explicitly deliver a report to your verified Feishu user only')
    delivery.add_argument('--input', required=True)
    delivery.add_argument('--lark-profile', required=True)
    delivery.add_argument('--receipt', required=True, help='Private NEW delivery receipt; preserves ambiguous attempts')
    delivery.add_argument('--apply', action='store_true')
    args = parser.parse_args(argv)
    if args.command == 'publish-report':
        from agentready_lark import commands_for_day
        commands_for_day(dt.date.today().isoformat(), lark_profile=args.lark_profile)
        result = publish_report(args.input, args.lark_profile, args.receipt, apply=args.apply)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    if args.command == 'personal-brief':
        result = build_personal_brief(args.date, live=args.live)
        data = json.dumps(result, ensure_ascii=False, indent=2) + '\n'
        if args.output: print(f'Personal brief created: {write_new(args.output, data)}')
        else: print(data, end='')
        return 1 if result.get('status') == 'partial' else 0
    if args.command == 'weekly-review':
        result = build_weekly_review(args.date, config=read_config(args.config) if args.config else None,
                                     period=args.period, live=args.live, fixture_dir=args.fixture_dir)
        data = (json.dumps(result, ensure_ascii=False, indent=2) + '\n'
                if args.format == 'json' else markdown_weekly(result))
        if args.output:
            print(f'Weekly review created: {write_new(args.output, data)}')
        else:
            print(data, end='')
        return 1 if result.get('status') == 'partial' else 0
    if args.command == 'brief':
        result = build_brief(args.date, live=args.live, fixture_dir=args.fixture_dir,
                             message_query=args.message_query, details=args.details, lark_profile=args.lark_profile)
        data = (json.dumps(result, ensure_ascii=False, indent=2)+'\n' if args.format == 'json'
                else markdown_brief(result))
        if args.output:
            print(f'Brief created: {write_new(args.output, data)}')
        else:
            print(data, end='')
        return 1 if result.get('status') == 'partial' else 0
    if args.command == 'wizard':
        if not sys.stdin.isatty():
            raise ValueError('Wizard needs an interactive terminal; use profiles or JSON config in CI')
        config = create_wizard_config(args.profile)
        dest = write_new(args.output, json.dumps(config, ensure_ascii=False, indent=2) + '\n')
        print(f'Nonsecret configuration created: {dest}')
        print(f'Next: python3 agentready.py plan --profile {args.profile} --config {dest}')
        return 0
    if args.command == 'verify':
        checked = verify_connector(args.service, args.url, live=args.live,
                                   allow_remote=args.allow_remote,
                                   token_env=args.token_env, mcp=args.mcp)
        print(json.dumps(checked, ensure_ascii=False, indent=2))
        return 0 if checked['reachability'] != 'failed' and checked['mcp_handshake'] != 'failed' and checked['auth'] not in ('failed', 'missing_local_env') else 1
    if args.command in ('coverage', 'report'):
        items = resolved(args.profile, args.config)
        if args.command == 'coverage':
            result = capability_coverage(items)
            if args.json:
                print(json.dumps({'profile': args.profile, 'capabilities': result}, ensure_ascii=False, indent=2))
            else:
                for cap in result:
                    print(f'{cap["label"]}: {", ".join(cap["selected_providers"]) or "NOT SELECTED"} ({cap["state"]})')
            return 0
        data = offline_report(args.profile, items)
        if args.output:
            print(f'Report created: {write_new(args.output, data)}')
        else:
            print(data, end='')
        return 0
    if args.command == 'catalog':
        for key, val in catalog().items():
            print(f'{key:22s} {val["label"]} ({val["category"]})')
        return 0
    items = resolved(args.profile, args.config)
    if args.command in ('doctor', 'plan'):
        summary(args.profile, items, args.json)
        if args.command == 'plan' and not args.json:
            print('\nInstall preview (macOS Homebrew; never run unless explicit install --apply):')
            print(bundle(items))
    elif args.command == 'permissions':
        print('Review permissions and sign-ins with the USER. Approval cannot be bypassed.')
        for name, spec in items:
            if spec.get('permissions'):
                print(f'\n{spec["label"]}:')
                for entry in spec['permissions']:
                    print('  [ ] ' + entry)
        print('\nSee docs/AUTHORIZATION.md and docs/CONNECTORS.md for manual steps.')
    elif args.command == 'inventory':
        inventory(items, args.output)
    elif args.command in ('brewfile', 'install'):
        # In install mode, leave already detected non-Homebrew or Homebrew apps alone.
        # The standalone Brewfile command intentionally renders the complete manifest.
        selected = items if args.command == 'brewfile' else [
            (name, spec) for name, spec in items if detect(spec) != 'found locally (access not verified)'
        ]
        content = bundle(selected)
        if args.command == 'brewfile':
            if args.output:
                target = Path(args.output).expanduser()
                if target.exists():
                    raise RuntimeError(f'Refusing to overwrite existing Brewfile: {target}')
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding='utf-8')
                print(f'Brewfile created: {target}')
            else:
                print(content)
        elif args.apply:
            skipped = len(items) - len(selected)
            if skipped:
                print(f'Skipping {skipped} already detected local component(s).')
            print('Approved install set:\n' + content)
            apply_brewfile(content)
            print('Installation attempted. OAuth, permissions, MCP and business tasks require separate verification.')
        else:
            print('DRY RUN — no changes made. To install on macOS, add --apply.\n' + content)
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, RuntimeError, LarkError, subprocess.CalledProcessError, OSError) as exc:
        print(f'AgentReady error: {exc}', file=sys.stderr)
        sys.exit(2)
